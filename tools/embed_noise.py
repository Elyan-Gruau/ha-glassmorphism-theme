#!/usr/bin/env python3
"""Bake assets/noise_texture.png into themes/glassmorphism.yaml as a base64 data URI.

HACS only downloads the theme YAML into /config/themes/<repo>/, and that
directory is not served over HTTP. Embedding the tile as a data URI keeps the
theme a single self-contained file with no /config/www setup for the user.

The source PNG is 256x256 RGBA, but its alpha channel is a constant and its
RGB channels are identical, so it is repacked as a grayscale+alpha crop: same
grain at 1:1 pixel scale, roughly a third of the base64 payload.

Usage:
    python3 tools/embed_noise.py [--tile 128]
"""

from __future__ import annotations

import argparse
import base64
import io
import pathlib
import re
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is required: pip install Pillow")

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "noise_texture.png"
THEME = ROOT / "themes" / "glassmorphism.yaml"

# The generator rewrites everything between these markers.
BEGIN = "  # BEGIN noise (generated by tools/embed_noise.py -- do not edit by hand)"
END = "  # END noise"

GRADIENT = "linear-gradient(0deg, rgba(81,81,81,0) 15%, rgba(0,0,0,0.1))"
CARD_COLOR = "rgba(30,30,40,0.35)"


def build_data_uri(tile: int) -> str:
    with Image.open(SOURCE) as src:
        rgba = src.convert("RGBA")

    red, _, _, alpha = rgba.split()
    if tile > rgba.width or tile > rgba.height:
        raise SystemExit(f"--tile {tile} exceeds source size {rgba.size}")

    box = (0, 0, tile, tile)
    packed = Image.merge("LA", (red.crop(box), alpha.crop(box)))

    buf = io.BytesIO()
    packed.save(buf, format="PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode("ascii")


def render_block(data_uri: str) -> str:
    # Single-line single-quoted scalars. A folded scalar (>-) would inject
    # whitespace into the base64 payload, and a double-quoted one would be cut
    # short by the double quotes CSS needs inside url(...).
    background = f'{GRADIENT}, url("{data_uri}"), {CARD_COLOR}'
    return "\n".join(
        [
            BEGIN,
            f"  ha-card-background: '{background}'",
            f"  glass-noise-image: 'url(\"{data_uri}\")'",
            END,
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tile", type=int, default=128, help="tile size in px (default 128)")
    args = parser.parse_args()

    block = render_block(build_data_uri(args.tile))
    theme = THEME.read_text(encoding="utf-8")

    pattern = re.compile(
        rf"^{re.escape(BEGIN)}$.*?^{re.escape(END)}$",
        re.DOTALL | re.MULTILINE,
    )
    if not pattern.search(theme):
        raise SystemExit(f"markers not found in {THEME}")

    THEME.write_text(pattern.sub(lambda _: block, theme), encoding="utf-8")
    print(f"embedded {args.tile}x{args.tile} tile -> {THEME.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
